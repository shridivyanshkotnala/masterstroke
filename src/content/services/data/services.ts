const scoreRelated = (target: ServiceSeed, candidate: ServiceSeed): number => {
  if (target.slug === candidate.slug) {
    return -1;
  }

  let score = 0;

  if (target.category === candidate.category) {
    score += 6;
  }

  const sharedTagCount = target.tags.filter((tag) => candidate.tags.includes(tag)).length;
  score += sharedTagCount * 3;

  if (candidate.slug.includes("consulting")) {
    score += 1;
  }

  return score;
};

export const getRelatedServices = (slug: string, limit: number = 5): ServicePageData[] => {
  const targetSeed = serviceSeeds.find((service) => service.slug === slug);

  if (!targetSeed) {
    return [];
  }

  const ranked = serviceSeeds
    .map((candidate) => ({
      slug: candidate.slug,
      score: scoreRelated(targetSeed, candidate),
    }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((entry) => servicesBySlug[entry.slug])
    .filter(Boolean);

  return ranked;
};
